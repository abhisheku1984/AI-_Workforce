export function generateReport(principal, { code, period, format = 'csv', filters = {} }) {
  const def = REPORTS[code];
  if (!def) throw Object.assign(new Error(`Unknown report "${code}".`), { status: 404 });
  if (!principal.permissions.has(def.permission) && !principal.isPlatformAdmin) {
    throw Object.assign(new Error('You do not have permission to generate this report.'), { status: 403, code: 'FORBIDDEN' });
  }

  const meta = {
    organization: principal.org?.name,
    generated_by: principal.user.email,
    generated_at: new Date().toISOString(),
    period: `${period.start} to ${period.end}`,
    filters: JSON.stringify(filters || {}),
    report: def.name,
    note: 'Generated by WorkforceIQ from the data in the platform. Fictional demonstration data may be present.',
  };

  let headers, rows, title = def.name;

  switch (code) {
    case 'utilization_summary': {
      const u = utilizationReport(principal, { period, filters });
      headers = def.columns;
      rows = [
        { metric: 'Headcount in scope', value: u.total.headcount, unit: 'people', definition: 'Active employees (including on leave and notice) in scope for the period.' },
        { metric: 'Available hours', value: u.total.available_hours, unit: 'hours', definition: u.definitions.available_hours },
        { metric: 'Allocated hours', value: u.total.allocated_hours, unit: 'hours', definition: u.definitions.allocated_hours },
        { metric: 'Utilized hours', value: u.total.utilized_hours, unit: 'hours', definition: u.definitions.utilized_hours },
        { metric: 'Unallocated hours', value: u.total.unallocated_hours, unit: 'hours', definition: u.definitions.unallocated_hours },
        { metric: 'Over-allocated hours', value: u.total.over_allocated_hours, unit: 'hours', definition: u.definitions.over_allocated_hours },
        { metric: 'Utilization %', value: u.total.utilization_pct, unit: '%', definition: u.definitions.utilization_pct },
        { metric: 'Allocation %', value: u.total.allocation_pct, unit: '%', definition: u.definitions.allocation_pct },
        { metric: 'Billable %', value: u.total.billable_pct, unit: '%', definition: u.definitions.billable_pct },
        { metric: 'Timesheet coverage', value: u.total.timesheet_coverage_pct, unit: '%', definition: 'Employees with at least one timesheet row in the period ÷ headcount.' },
      ];
      break;
    }
    case 'department_utilization': {
      const u = utilizationReport(principal, { period, filters });
      headers = def.columns;
      rows = u.byDepartment.map((d) => ({ ...d, department: d.key }));
      break;
    }
    case 'employee_capacity': {
      const u = utilizationReport(principal, { period, filters });
      const costAllowed = maySeeCost(principal);
      headers = ['employee_code', 'full_name', 'department', 'business_unit', 'location', 'designation', 'status',
        'available_hours', 'allocated_hours', 'utilized_hours', 'unallocated_hours', 'over_allocated_hours',
        'allocation_pct', 'utilization_pct', 'project_count', ...(costAllowed ? ['annual_cost', 'cost_currency'] : [])];
      const costById = new Map();
      if (costAllowed) {
        const db = getDb();
        for (const r of db.prepare('SELECT id, annual_cost, cost_currency FROM employees WHERE org_id = ?').all(principal.orgId)) {
          costById.set(r.id, r);
        }
      }
      rows = u.employees.map((e) => ({
        ...e,
        ...(costAllowed ? { annual_cost: costById.get(e.employee_id)?.annual_cost ?? '', cost_currency: costById.get(e.employee_id)?.cost_currency ?? '' } : {}),
      }));
      break;
    }
    case 'project_demand': {
      const d = demandAnalysis(principal);
      headers = def.columns;
      rows = d.gaps;
      break;
    }
    case 'allocation_register': {
      const db = getDb();
      const rowsRaw = db.prepare(`SELECT a.*, e.employee_code, e.full_name AS employee_name, p.code AS project_code, p.name AS project_name
          FROM allocations a JOIN employees e ON e.id = a.employee_id LEFT JOIN projects p ON p.id = a.project_id
          WHERE a.org_id = ? AND a.status <> 'cancelled' AND a.start_date <= ? AND a.end_date >= ?
          ORDER BY e.full_name, a.start_date`).all(principal.orgId, period.end, period.start);
      headers = def.columns;
      rows = rowsRaw;
      break;
    }
    case 'workforce_cost': {
      if (!maySeeCost(principal) && !maySeeFinance(principal)) throw Object.assign(new Error('Cost permission required.'), { status: 403 });
      const fin = financialAnalysis(principal, { period, filters });
      headers = def.columns;
      rows = [
        ...fin.byDepartment.map((d) => ({ scope: 'Department', name: d.name, headcount: d.headcount, period_cost: d.period_cost, idle_cost: d.idle_cost, currency: principal.org?.currency || 'INR' })),
        ...fin.byBusinessUnit.map((d) => ({ scope: 'Business unit', name: d.name, headcount: d.headcount, period_cost: d.period_cost, idle_cost: d.idle_cost, currency: principal.org?.currency || 'INR' })),
      ];
      break;
    }
    case 'data_quality': {
      const u = utilizationReport(principal, { period, filters });
      const db = getDb();
      const counts = db.prepare(`SELECT
          (SELECT COUNT(*) FROM employees WHERE org_id = ?) employees,
          (SELECT COUNT(*) FROM employees WHERE org_id = ? AND annual_cost IS NULL) employees_without_cost,
          (SELECT COUNT(*) FROM projects WHERE org_id = ?) projects,
          (SELECT COUNT(*) FROM allocations WHERE org_id = ?) allocations,
          (SELECT COUNT(*) FROM timesheets WHERE org_id = ?) timesheets,
          (SELECT COUNT(*) FROM invoices WHERE org_id = ?) invoices`).get(...Array(6).fill(principal.orgId));
      headers = def.columns;
      rows = [
        { check: 'Employees', value: counts.employees, unit: 'records', status: 'info' },
        { check: 'Projects', value: counts.projects, unit: 'records', status: 'info' },
        { check: 'Allocations', value: counts.allocations, unit: 'records', status: 'info' },
        { check: 'Timesheet rows', value: counts.timesheets, unit: 'records', status: counts.timesheets ? 'ok' : 'missing' },
        { check: 'Invoices', value: counts.invoices, unit: 'records', status: counts.invoices ? 'ok' : 'missing' },
        { check: 'Employees without cost', value: counts.employees_without_cost, unit: 'records', status: counts.employees_without_cost ? 'partial' : 'ok' },
        { check: 'Timesheet coverage (period)', value: u.total.timesheet_coverage_pct, unit: '%', status: u.total.timesheet_coverage_pct >= 90 ? 'ok' : 'partial' },
      ];
      break;
    }
    case 'audit_trail': {
      const db = getDb();
      headers = def.columns;
      rows = db.prepare(`SELECT created_at, actor_email, action, entity_type, entity_id, summary FROM audit_events
          WHERE org_id = ? AND created_at >= ? AND created_at <= ? ORDER BY created_at DESC LIMIT 5000`)
        .all(principal.orgId, `${period.start}T00:00:00.000Z`, `${period.end}T23:59:59.999Z`);
      break;
    }
    default:
      throw Object.assign(new Error('Report not implemented.'), { status: 400 });
  }

  const filename = `${code}_${period.start}_${period.end}_${Date.now()}.${format}`;
  const outPath = path.join(config.exportsDir, filename);
  const metaRows = Object.entries(meta).map(([k, v]) => ({ field: k, value: v }));

  if (format === 'xlsx') {
    const buf = toXlsxMultiSheet([
      { name: 'About', headers: ['Field', 'Value'], rows: metaRows.map((m) => ({ Field: m.field, Value: m.value })) },
      { name: 'Data', headers, rows: rows.map((r) => { const o = {}; headers.forEach((h) => { o[h] = r[h] ?? ''; }); return o; }) },
    ]);
    fs.writeFileSync(outPath, buf);
  } else {
    const headerBlock = `# WorkforceIQ report: ${def.name}\n# Organisation: ${meta.organization}\n# Period: ${meta.period}\n# Generated: ${meta.generated_at} by ${meta.generated_by}\n# Filters: ${meta.filters}\n# Note: ${meta.note}\n`;
    fs.writeFileSync(outPath, headerBlock + toCsv(headers, rows.map((r) => {
      const o = {};
      headers.forEach((h) => { o[h] = r[h] ?? ''; });
      return o;
    })), 'utf8');
  }

  const db = getDb();
  db.prepare(`INSERT INTO report_runs (org_id, report_code, params, format, row_count, file_path, generated_by, created_at)
      VALUES (?, ?, ?, ?, ?, ?, ?, ?)`)
    .run(principal.orgId, code, JSON.stringify({ period, filters }), format, rows.length, outPath, principal.user.id, now());

  return { path: outPath, filename, rowCount: rows.length, format, headers, rows, meta };
}

export function listReportHistory(orgId, limit = 50) {
  return getDb().prepare(`SELECT rr.*, u.full_name AS generated_by_name FROM report_runs rr
      LEFT JOIN users u ON u.id = rr.generated_by WHERE rr.org_id = ? ORDER BY rr.created_at DESC LIMIT ?`)
    .all(orgId, limit);
}
